"""The internal CA that issues short-lived device certificates (§3.1, §11.2, §13.1, §14.2, §14.3).

What this module is, and what it is deliberately not
---------------------------------------------------
A **single-level** CA whose only job is to turn an agent's CSR into a client certificate that
lives at most `DEVICE_CERT_TTL_HOURS` (default 24). It is the enrolment half of §14.3's
`PairedDevice` identity: the strength claim is "no long-lived key on the device, and possession
bound to an operator action", not platform attestation. §14.3 says so explicitly and this module
does not improve on it.

It is not a PKI. There is no intermediate, no CRL, no OCSP and no path builder. Revocation is
**not** a certificate concern here — §11.2 makes it Redis-authoritative and checked per message
(Q-16), which is strictly stronger than a CRL an agent would fetch on its own schedule, and much
simpler than maintaining a revocation list for credentials that expire in a day anyway.

Why the CA rewrites the subject instead of honouring the CSR's
-------------------------------------------------------------
§3.1 has the agent build its CSR **before** it knows its device id — the id only exists once the
exchange succeeds — so the CSR's subject is, by construction, not the identity anyone wants. The
CA therefore ignores it and issues `CN=<device_id>`. That is the safer direction regardless of
timing: a CSR subject is caller-supplied data on an unauthenticated route, and a CA that copies
caller-supplied data into the identity field of a credential is a CA that lets the caller choose
who it is. What the CSR contributes is the **public key** and the proof that the requester holds
the matching private key; the identity comes from the row the backend created.

Why the fingerprint is the authorisation input and the chain is only a precondition
---------------------------------------------------------------------------------
`verify_chain` answers "did this CA issue this certificate, and is it currently valid". It does
**not** answer "is this the certificate that belongs to device X" — `agent_devices.cert_fingerprint`
answers that, and §3.1's handshake checks both. Keeping them separate matters: a chain check alone
would accept any certificate this CA ever issued, including one issued to a different device, so
the two checks are not redundant and neither is sufficient.

Key custody, stated as the open question it is
---------------------------------------------
In development the CA key lives in `.env`, generated by `scripts/init-ca.sh`, git-ignored, never
committed. §14.2 calls it "a genuinely new high-value secret" and production custody is **OQ-31**.
This module holds the key in memory for the process lifetime, which is the same exposure the
envelope pepper already has, and it never logs, returns or serialises it.
"""

